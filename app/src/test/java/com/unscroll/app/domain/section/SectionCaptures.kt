    /** One visible node; "-" is a node without an ID, "@x" an ID in the screen's package. */
    private fun n(id: String, className: String, selected: Boolean = false) = Node(id, className, selected)

    private class Node(val id: String, val className: String, val selected: Boolean)

    private fun screen(pkg: String, window: String, vararg nodes: Node) = SectionScreen(
        packageName = pkg,
        windowClassName = window,
        // The log is flat (depth-first, deduplicated); the detector only looks at visible nodes
        // anywhere in the tree, so one root holding them all is equivalent.
        root = SectionNode(
            className = "android.widget.FrameLayout",
            children = nodes.map {
                SectionNode(
                    viewId = when {
                        it.id == "-" -> null
                        it.id.startsWith("@") -> "$pkg:id/${it.id.drop(1)}"
                        else -> it.id
                    },
                    className = it.className,
                    isSelected = it.selected,
                )
            },
        ),
    )
